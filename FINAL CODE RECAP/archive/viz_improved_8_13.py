def chart9_coefficient_comparison():
    """
    Single grouped bar chart replacing the 3-panel layout.
    Each variable has 3 bars (LASSO, Ridge, Elastic Net) side by side,
    making cross-model comparison immediate.
    """
    tbl = pd.read_csv(os.path.join(NB5, 'coefficient_summary_table.csv'))
    # Exclude L1_ECI
    tbl = tbl[~tbl['Feature'].str.contains('L1_ECI', na=False)]
    # Top 12 by Elastic Net absolute coefficient
    tbl['abs_en'] = tbl['Elastic Net'].abs()
    top = tbl.nlargest(12, 'abs_en').reset_index(drop=True)
    top = top.sort_values('abs_en', ascending=True).reset_index(drop=True)   # bottom → top

