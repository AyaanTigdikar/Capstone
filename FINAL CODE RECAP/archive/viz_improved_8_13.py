# CHART 12 — Actual vs Predicted (shaded directional quadrants)
# =============================================================================
def chart12_actual_vs_predicted():
    """
    Scatter with 45° line + shaded quadrants:
    - Upper-right & lower-left (diagonal): correctly predicted direction
    - Upper-left & lower-right (off-diagonal): wrong direction
    Outliers labelled; OLS trend line retained.
    """
    preds = pd.read_csv(os.path.join(NB5, 'test_predictions.csv'))
    best_model = preds['Best_Level_Model'].iloc[0]

    actual = preds['Actual_ECI'].values
    pred   = preds['Predicted_ECI'].values
    codes  = preds['Country Code'].values
    names  = preds['Country Name'].values

    lims = [min(actual.min(), pred.min()) - 0.08,
            max(actual.max(), pred.max()) + 0.08]

    # R² and RMSE
    from sklearn.metrics import r2_score, mean_squared_error
    r2   = r2_score(actual, pred)
    rmse = np.sqrt(mean_squared_error(actual, pred))

    # OLS trend
    z   = np.polyfit(actual, pred, 1)
    p   = np.poly1d(z)
    x_t = np.linspace(lims[0], lims[1], 100)

    # Outlier flagging: largest |residual|
    resid = np.abs(actual - pred)
    top_n = np.argsort(resid)[::-1][:6]
    label_set = set(top_n)

    fig = go.Figure()

    # ── Quadrant shading ─────────────────────────────────────────────────────
    # Correct direction: upper-right (actual>0, pred>0) + lower-left (<0,<0)
    mid = 0.0
    shade_correct = 'rgba(46,125,74,0.07)'
    shade_wrong   = 'rgba(194,58,58,0.07)'

    # lower-left correct
    fig.add_shape(type='rect', x0=lims[0], x1=mid, y0=lims[0], y1=mid,
                  fillcolor=shade_correct, line=dict(width=0), layer='below')
    # upper-right correct
    fig.add_shape(type='rect', x0=mid, x1=lims[1], y0=mid, y1=lims[1],
                  fillcolor=shade_correct, line=dict(width=0), layer='below')
    # upper-left wrong (actual<0, pred>0)
    fig.add_shape(type='rect', x0=lims[0], x1=mid, y0=mid, y1=lims[1],
                  fillcolor=shade_wrong,   line=dict(width=0), layer='below')
    # lower-right wrong (actual>0, pred<0)
    fig.add_shape(type='rect', x0=mid, x1=lims[1], y0=lims[0], y1=mid,
                  fillcolor=shade_wrong,   line=dict(width=0), layer='below')

    # 45° line
    fig.add_trace(go.Scatter(
        x=[lims[0], lims[1]], y=[lims[0], lims[1]],
        mode='lines', line=dict(color=PALETTE['red'], width=1.5, dash='dash'),
        name='45° line', showlegend=True,
    ))

    # OLS fit
    fig.add_trace(go.Scatter(
        x=x_t.tolist(), y=p(x_t).tolist(),
        mode='lines', line=dict(color=PALETTE['green'], width=2),
        name=f'OLS fit (slope={z[0]:.2f})',
    ))

    # Scatter: non-outliers
    mask_normal = np.ones(len(actual), dtype=bool)
    mask_normal[list(label_set)] = False
    fig.add_trace(go.Scatter(
        x=actual[mask_normal], y=pred[mask_normal],
        mode='markers',
        marker=dict(size=7, color=PALETTE['blue'], opacity=0.65,
                    line=dict(color='white', width=0.5)),
        name='Test observations',
        customdata=np.stack([codes[mask_normal], names[mask_normal]], axis=1),
        hovertemplate='<b>%{customdata[1]}</b> (%{customdata[0]})<br>'
                      'Actual: %{x:.3f}<br>Predicted: %{y:.3f}<extra></extra>',
    ))

    # Scatter: outliers (labelled)
    out_idx = list(label_set)
    fig.add_trace(go.Scatter(
        x=actual[out_idx], y=pred[out_idx],
        mode='markers+text',
        marker=dict(size=9, color=PALETTE['orange'], opacity=0.9,
                    line=dict(color='white', width=1)),
        text=codes[out_idx],
        textposition='top center',
        textfont=dict(size=9, color='#333'),
        name='Largest residuals',
        customdata=np.stack([codes[out_idx], names[out_idx]], axis=1),
        hovertemplate='<b>%{customdata[1]}</b><br>'
                      'Actual: %{x:.3f}<br>Predicted: %{y:.3f}<extra></extra>',
    ))

    # Zero axes
    fig.add_hline(y=0, line=dict(color=GRID, width=1))
    fig.add_vline(x=0, line=dict(color=GRID, width=1))

    fig.update_layout(**base_layout(
        height=600,
        margin=dict(l=70, r=80, t=80, b=70),
        xaxis=dict(
            title=dict(text='Actual ECI (test set 2015–2019)', font=dict(size=13)),
            range=lims, gridcolor=GRID, gridwidth=0.5,
        ),
        yaxis=dict(
            title=dict(text='Predicted ECI', font=dict(size=13)),
            range=lims, gridcolor=GRID, gridwidth=0.5,
        ),
        legend=dict(
            font=dict(size=10), bgcolor='rgba(250,250,250,0.9)',
            bordercolor=GRID, borderwidth=1,
        ),
    ))
    save(fig, 'chart12_actual_vs_predicted', w=950, h=600)


