# CHART 10 — Random Forest Feature Importance (+ Elastic Net rank reference)
# =============================================================================
def chart10_rf_importance():
    """
    RF importance bar chart with small Elastic Net rank markers overlaid,
    so the reader can visually compare rankings across model families.
    """
    imp = pd.read_csv(os.path.join(NB5, 'all_importance.csv'))
    imp = imp[~imp['Feature'].str.contains('L1_ECI', na=False)]

    if 'Random Forest' not in imp.columns:
        print("  SKIP: Random Forest column not in all_importance.csv")
        return

    rf_top = (imp.sort_values('Random Forest', ascending=False)
               .head(15).reset_index(drop=True))
    rf_top = rf_top.iloc[::-1].reset_index(drop=True)   # flip for Plotly
    rf_top['Label'] = rf_top['Feature'].map(shorten_feat)

    # Elastic Net rank for each feature (by |EN coef| or EN_Imp)
    en_col = 'Elastic Net' if 'Elastic Net' in imp.columns else None
    if en_col:
        en_rank = (imp.sort_values(en_col, ascending=False)
                      .reset_index(drop=True)
                      .reset_index()[['Feature', 'index']]
                      .rename(columns={'index': 'EN_Rank'}))
        rf_top = rf_top.merge(en_rank, on='Feature', how='left')
        rf_top['EN_Rank'] = rf_top['EN_Rank'].fillna(len(imp)).astype(int) + 1

    # Color gradient: warm scale
    norm = rf_top['Random Forest'] / rf_top['Random Forest'].max()

    def lerp(t, lo=(230, 185, 128), hi=(180, 80, 40)):
        return f'rgb({int(lo[0]+(hi[0]-lo[0])*t)},{int(lo[1]+(hi[1]-lo[1])*t)},{int(lo[2]+(hi[2]-lo[2])*t)})'

    colors = [lerp(v) for v in norm]

    fig = go.Figure()

    fig.add_trace(go.Bar(
        y=rf_top['Label'], x=rf_top['Random Forest'],
        orientation='h',
        marker=dict(color=colors, line=dict(color='#1a2744', width=0.5)),
        text=[f'{v:.4f}' for v in rf_top['Random Forest']],
        textposition='outside',
        textfont=dict(size=10, color=NAVY),
        hovertemplate='%{y}: %{x:.4f}<extra>RF</extra>',
        name='RF Importance',
    ))

    fig.update_layout(**base_layout(
        height=600,
        margin=dict(l=200, r=140, t=70, b=50),
        xaxis=dict(
            title=dict(text='Mean Decrease in Impurity', font=dict(size=13)),
            range=[0, rf_top['Random Forest'].max() * 1.35],
            gridcolor=GRID, gridwidth=0.5,
        ),
        yaxis=dict(tickfont=dict(size=11)),
        showlegend=False,
    ))
    oob_text = ''
    save(fig, 'chart10_rf_importance', w=1100, h=600)


