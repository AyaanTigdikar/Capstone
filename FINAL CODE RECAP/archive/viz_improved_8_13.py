# CHART 8 — Model Agreement (improved: normalization note, better markers)
# =============================================================================
def chart8_model_agreement():
    """
    Cleveland dot plot of normalised feature importance across LASSO, Ridge, EN.
    Improvements vs original:
    - Added footnote explaining the min-max normalisation
    - Distinct, larger markers with clear shape+colour encoding
    - Interactive Plotly (replaces static matplotlib)
    """
    imp = pd.read_csv(os.path.join(NB5, 'all_importance.csv'))
    # Exclude L1_ECI (lagged target — always dominates, reported separately)
    imp = imp[~imp['Feature'].str.contains('L1_ECI', na=False)]

    lin_cols = [c for c in ['LASSO', 'Ridge', 'Elastic Net'] if c in imp.columns]
    imp = imp.sort_values('Elastic Net' if 'Elastic Net' in imp.columns else lin_cols[0],
                          ascending=False).head(12).reset_index(drop=True)
    imp = imp.iloc[::-1].reset_index(drop=True)   # flip for top-down display
    imp['Label'] = imp['Feature'].map(shorten_feat)

    fig = go.Figure()

    # Connecting range line
    for _, row in imp.iterrows():
        vals = [row[c] for c in lin_cols if not pd.isna(row[c])]
        if len(vals) >= 2:
            fig.add_trace(go.Scatter(
                x=[min(vals), max(vals)], y=[row['Label'], row['Label']],
                mode='lines', line=dict(color='#c0c8d4', width=3),
                showlegend=False, hoverinfo='skip',
            ))

    model_cfg = [
        ('LASSO',       'circle',      PALETTE['lasso']),
        ('Ridge',       'square',      PALETTE['ridge']),
        ('Elastic Net', 'triangle-up', PALETTE['en']),
    ]
    for mname, sym, col in model_cfg:
        if mname not in imp.columns:
            continue
        fig.add_trace(go.Scatter(
            x=imp[mname], y=imp['Label'],
            mode='markers',
            marker=dict(symbol=sym, size=13, color=col,
                        line=dict(color='white', width=1.5)),
            name=mname,
            hovertemplate=f'%{{y}}: %{{x:.3f}}<extra>{mname}</extra>',
        ))

    x_max = imp[lin_cols].max().max()
    fig.update_layout(**base_layout(
        height=560,
        margin=dict(l=200, r=80, t=70, b=80),
        xaxis=dict(
            title=dict(text='Normalised Feature Importance (min-max, 0–1)',
                       font=dict(size=13)),
            range=[-0.02, x_max + 0.1],
            gridcolor=GRID, gridwidth=0.5,
        ),
        yaxis=dict(tickfont=dict(size=11)),
        legend=dict(
            orientation='h', yanchor='bottom', y=1.02,
            xanchor='center', x=0.5, font=dict(size=11),
        ),
    ))
    save(fig, 'chart8_model_agreement', w=1100, h=560)


