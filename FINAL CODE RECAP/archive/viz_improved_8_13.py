# CHART 11 — Train vs Test R²/RMSE (Cleveland dot plot)
# =============================================================================
def chart11_train_vs_test():
    """
    Connected dot plot (Cleveland style) replacing the grouped bar chart.
    Each model has two dots (Train vs Test) connected by a line.
    The gap is visually prominent without needing delta labels.
    Shows both ECI and ΔECI targets in two subplots.
    """
    perf_l = pd.read_csv(os.path.join(NB5, 'model_performance_level.csv'))
    perf_d = pd.read_csv(os.path.join(NB5, 'model_performance_delta.csv'))

    fig = make_subplots(
        rows=1, cols=2,
        horizontal_spacing=0.14,
    )

    for col_idx, (perf, title) in enumerate([(perf_l, 'ECI'), (perf_d, 'ΔECI')], 1):
        models = perf['Model'].tolist()
        train_r2 = perf['Train R²'].tolist()
        test_r2  = perf['Test R²'].tolist()

        # Connecting lines
        for i, (tr, te, mname) in enumerate(zip(train_r2, test_r2, models)):
            fig.add_trace(go.Scatter(
                x=[tr, te], y=[mname, mname],
                mode='lines',
                line=dict(color='#c0c8d4', width=2.5),
                showlegend=False, hoverinfo='skip',
            ), row=1, col=col_idx)

        # Train dots
        fig.add_trace(go.Scatter(
            x=train_r2, y=models,
            mode='markers',
            marker=dict(symbol='circle', size=13, color=PALETTE['blue'],
                        line=dict(color='white', width=1.5)),
            name='Train R²' if col_idx == 1 else '',
            showlegend=(col_idx == 1),
            hovertemplate='%{y} Train: %{x:.3f}<extra></extra>',
        ), row=1, col=col_idx)

        # Test dots
        fig.add_trace(go.Scatter(
            x=test_r2, y=models,
            mode='markers',
            marker=dict(symbol='diamond', size=13, color=PALETTE['red'],
                        line=dict(color='white', width=1.5)),
            name='Test R²' if col_idx == 1 else '',
            showlegend=(col_idx == 1),
            hovertemplate='%{y} Test: %{x:.3f}<extra></extra>',
        ), row=1, col=col_idx)

        fig.update_xaxes(
            title_text='R²' if col_idx == 1 else '',
            gridcolor=GRID, gridwidth=0.5,
            row=1, col=col_idx,
        )
        fig.update_yaxes(row=1, col=col_idx, tickfont=dict(size=11))

    fig.update_layout(**base_layout(
        height=440,
        margin=dict(l=130, r=60, t=80, b=60),
        legend=dict(
            orientation='h', yanchor='bottom', y=1.06,
            xanchor='center', x=0.5, font=dict(size=11),
        ),
    ))

    # Panel labels — "ECI Level" and "ΔECI" above each subplot
    for x_paper, panel_label in [(0.23, 'ECI Level'), (0.77, 'ΔECI')]:
        fig.add_annotation(
            x=x_paper, y=1.04, xref='paper', yref='paper',
            text=f'<b>{panel_label}</b>',
            showarrow=False,
            font=dict(size=12, color=NAVY, family=FONT),
            xanchor='center', yanchor='bottom',
        )

    save(fig, 'chart11_train_vs_test', w=1100, h=440)


